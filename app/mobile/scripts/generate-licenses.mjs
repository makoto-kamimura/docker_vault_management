// Generates src/features/settings/licenses.generated.ts from package.json dependencies.
// Run: node scripts/generate-licenses.mjs  (also wired as `pnpm licenses`).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const entries = [];
for (const name of Object.keys(pkg.dependencies ?? {}).sort()) {
  if (name.startsWith('@localvault/')) continue;
  const p = join(root, 'node_modules', name, 'package.json');
  if (!existsSync(p)) continue;
  const meta = JSON.parse(readFileSync(p, 'utf8'));
  const license =
    typeof meta.license === 'string' ? meta.license : (meta.license?.type ?? 'UNKNOWN');
  entries.push({ name, version: meta.version ?? '', license });
}
const out = `// GENERATED by scripts/generate-licenses.mjs - do not edit.\nexport const LICENSES: readonly { name: string; version: string; license: string }[] = ${JSON.stringify(entries, null, 2)};\n`;
writeFileSync(join(root, 'src/features/settings/licenses.generated.ts'), out);
console.log(`wrote ${entries.length} entries`);
